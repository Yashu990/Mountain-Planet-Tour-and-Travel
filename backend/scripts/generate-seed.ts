// Builds supabase/seed.sql from the app's bundled content (mobile/src/data),
// so the database starts with exactly the same tours, guides and destinations.
//
//   node scripts/generate-seed.ts        (Node 22.18+ / 23.6+ runs TypeScript directly)

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { tours, guides } from '../../mobile/src/data/tours.ts';
import { destinations, slug } from '../../mobile/src/data/destinations.ts';
import { stories } from '../../mobile/src/data/placeStories.ts';
import { stays } from '../../mobile/src/data/stays.ts';

const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(', ')}]` : `'{}'::text[]`);
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = [
  '-- GENERATED by scripts/generate-seed.ts from mobile/src/data — do not edit by hand.',
  '-- Re-running it upserts the content, so edits made in the dashboard to these rows are overwritten.',
  '',
];

lines.push('insert into public.tours (slug, title, region, category, days, price_usd, difficulty, max_alt_m, season, img, ratio, rating, reviews, group_size, tags, summary, highlights, itinerary, includes, sort_order) values');
lines.push(
  tours
    .map(
      (t, i) =>
        `  (${[q(t.slug), q(t.title), q(t.region), q(t.category), t.days, t.price, q(t.difficulty), t.maxAlt, q(t.season), q(t.img), t.ratio, t.rating, t.reviews, q(t.groupSize), arr(t.tags), q(t.summary), arr(t.highlights), json(t.itinerary), arr(t.includes), i].join(', ')})`,
    )
    .join(',\n'),
);
lines.push(
  'on conflict (slug) do update set title = excluded.title, region = excluded.region, category = excluded.category, days = excluded.days, price_usd = excluded.price_usd, difficulty = excluded.difficulty, max_alt_m = excluded.max_alt_m, season = excluded.season, img = excluded.img, ratio = excluded.ratio, rating = excluded.rating, reviews = excluded.reviews, group_size = excluded.group_size, tags = excluded.tags, summary = excluded.summary, highlights = excluded.highlights, itinerary = excluded.itinerary, includes = excluded.includes, sort_order = excluded.sort_order;',
  '',
);

lines.push('insert into public.guides (slug, title, kicker, img, ratio, minutes, intro, sections, sort_order) values');
lines.push(guides.map((g, i) => `  (${[q(g.slug), q(g.title), q(g.kicker), q(g.img), g.ratio, g.minutes, q(g.intro), json(g.sections), i].join(', ')})`).join(',\n'));
lines.push(
  'on conflict (slug) do update set title = excluded.title, kicker = excluded.kicker, img = excluded.img, ratio = excluded.ratio, minutes = excluded.minutes, intro = excluded.intro, sections = excluded.sections, sort_order = excluded.sort_order;',
  '',
);

lines.push('insert into public.destinations (slug, name, area, img, alt, fact, best, q, story, highlights, sort_order) values');
lines.push(
  destinations
    .map((d, i) => {
      const s = stories[d.name];
      return `  (${[q(slug(d.name)), q(d.name), q(d.area), q(d.img), q(d.alt), q(d.fact), q(d.best), q(d.q), q(s?.story ?? ''), arr(s?.highlights ?? []), i].join(', ')})`;
    })
    .join(',\n'),
);
lines.push(
  'on conflict (slug) do update set name = excluded.name, area = excluded.area, img = excluded.img, alt = excluded.alt, fact = excluded.fact, best = excluded.best, q = excluded.q, story = excluded.story, highlights = excluded.highlights, sort_order = excluded.sort_order;',
  '',
);

lines.push('-- Sample stays (is_sample = true): placeholders until real partner hotels / homestays are added.');
lines.push('insert into public.stays (slug, kind, name, city, address, images, rating, reviews, max_guests, bedrooms, beds, baths, price_usd_night, star_rating, free_cancellation, breakfast_included, amenities, description, is_sample, sort_order) values');
lines.push(
  stays
    .map((s, i) => `  (${[q(s.slug), q(s.kind), q(s.name), q(s.city), q(s.address), arr(s.images), s.rating ?? 'null', s.reviews, s.maxGuests, s.bedrooms, s.beds, s.baths, s.priceUsdNight ?? 'null', s.starRating ?? 'null', s.freeCancellation, s.breakfastIncluded, arr(s.amenities), q(s.description), s.isSample, i].join(', ')})`)
    .join(',\n'),
);
lines.push(
  'on conflict (slug) do update set kind = excluded.kind, name = excluded.name, city = excluded.city, address = excluded.address, images = excluded.images, rating = excluded.rating, reviews = excluded.reviews, max_guests = excluded.max_guests, bedrooms = excluded.bedrooms, beds = excluded.beds, baths = excluded.baths, price_usd_night = excluded.price_usd_night, star_rating = excluded.star_rating, free_cancellation = excluded.free_cancellation, breakfast_included = excluded.breakfast_included, amenities = excluded.amenities, description = excluded.description, is_sample = excluded.is_sample, sort_order = excluded.sort_order;',
  '',
);

const out = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out}: ${tours.length} tours, ${guides.length} guides, ${destinations.length} destinations, ${stays.length} sample stays.`);
